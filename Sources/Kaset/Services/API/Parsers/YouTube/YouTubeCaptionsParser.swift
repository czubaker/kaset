import Foundation

// MARK: - YouTubeCaptionsParser

/// Reads a video's caption tracks from the `player` response
/// (`captions.playerCaptionsTracklistRenderer.captionTracks[]`, each with
/// `baseUrl`, `languageCode`, `name`, and `kind: "asr"` for speech
/// recognition), and the text of a track fetched as `fmt=json3`
/// (`events[].segs[].utf8`). Verified with api-explorer, November 2026.
enum YouTubeCaptionsParser {
    static func tracks(fromPlayer data: [String: Any]) -> [YouTubeTranscriptTrack] {
        guard let captions = data["captions"] as? [String: Any],
              let renderer = captions["playerCaptionsTracklistRenderer"] as? [String: Any],
              let tracks = renderer["captionTracks"] as? [[String: Any]]
        else { return [] }
        return tracks.compactMap { track in
            guard let base = track["baseUrl"] as? String,
                  let url = URL(string: base),
                  Self.isTimedTextURL(url),
                  let languageCode = track["languageCode"] as? String
            else { return nil }
            return YouTubeTranscriptTrack(
                baseURL: url,
                languageCode: languageCode,
                name: YouTubeItemParser.text(from: track["name"]) ?? languageCode,
                isAutoGenerated: track["kind"] as? String == "asr"
            )
        }
    }

    /// The track to read: written captions in one of `preferredLanguages`,
    /// then written English, then the speech-recognition track (the video's
    /// own language), then whatever there is.
    static func preferredTrack(
        among tracks: [YouTubeTranscriptTrack],
        preferredLanguages: [String]
    ) -> YouTubeTranscriptTrack? {
        let written = tracks.filter { !$0.isAutoGenerated }
        for language in preferredLanguages.map(Self.baseLanguage) {
            if let track = written.first(where: { Self.baseLanguage($0.languageCode) == language }) {
                return track
            }
        }
        return written.first { Self.baseLanguage($0.languageCode) == "en" }
            ?? tracks.first(where: \.isAutoGenerated)
            ?? tracks.first
    }

    /// The URL that fetches `track` as JSON.
    static func jsonURL(for track: YouTubeTranscriptTrack) -> URL? {
        guard var components = URLComponents(url: track.baseURL, resolvingAgainstBaseURL: false) else { return nil }
        var items = (components.queryItems ?? []).filter { $0.name != "fmt" }
        items.append(URLQueryItem(name: "fmt", value: "json3"))
        components.queryItems = items
        return components.url
    }

    /// A json3 track's text as one paragraph. Each event is a cue; written
    /// captions end a cue without a space, so cues are joined with one.
    static func transcript(fromJSON3 data: [String: Any]) -> String {
        let events = data["events"] as? [[String: Any]] ?? []
        let text = events
            .map { event in
                (event["segs"] as? [[String: Any]] ?? []).compactMap { $0["utf8"] as? String }.joined()
            }
            .joined(separator: " ")
        return text
            .components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
    }

    /// Only YouTube's own timed-text endpoint is fetched.
    static func isTimedTextURL(_ url: URL) -> Bool {
        guard url.scheme == "https", let host = url.host?.lowercased() else { return false }
        return (host == "youtube.com" || host.hasSuffix(".youtube.com")) && url.path == "/api/timedtext"
    }

    private static func baseLanguage(_ code: String) -> String {
        String(code.lowercased().split(separator: "-").first ?? Substring(code.lowercased()))
    }
}
