import Foundation

// MARK: - YouTubeTranscriptTrack

/// One of a video's caption tracks as the player response lists it, for
/// reading its text (the player's own captions menu uses YouTubeCaptionTrack).
struct YouTubeTranscriptTrack: Hashable {
    /// YouTube's timed-text URL for the track.
    let baseURL: URL
    let languageCode: String
    let name: String
    /// Speech recognition rather than captions someone wrote.
    let isAutoGenerated: Bool
}
