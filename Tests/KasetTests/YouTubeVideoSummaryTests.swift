import Foundation
import Testing
@testable import Kaset

// MARK: - YouTubeVideoSummaryTests

/// Caption tracks from the player response and their json3 text (captured
/// with api-explorer, November 2026), how a transcript is split for the
/// on-device model, and the summary card's states.
@Suite(.serialized, .tags(.parser))
@MainActor
struct YouTubeVideoSummaryTests {
    private static func track(_ code: String, asr: Bool = false, host: String = "www.youtube.com") -> [String: Any] {
        var track: [String: Any] = [
            "baseUrl": "https://\(host)/api/timedtext?v=video01&lang=\(code)&fmt=srv3",
            "languageCode": code,
            "name": ["simpleText": code.uppercased()],
        ]
        if asr {
            track["kind"] = "asr"
        }
        return track
    }

    private static func player(_ tracks: [[String: Any]]) -> [String: Any] {
        ["captions": ["playerCaptionsTracklistRenderer": ["captionTracks": tracks]]]
    }

    private static func transcriptTrack(_ code: String, asr: Bool = false) -> YouTubeTranscriptTrack {
        YouTubeTranscriptTrack(
            baseURL: URL(string: "https://www.youtube.com/api/timedtext?lang=\(code)\(asr ? "&kind=asr" : "")") ?? URL(fileURLWithPath: "/"),
            languageCode: code,
            name: code,
            isAutoGenerated: asr
        )
    }

    @Test("Caption tracks come from the player response; only YouTube's timed-text URLs are kept")
    func parsesTracks() {
        let tracks = YouTubeCaptionsParser.tracks(fromPlayer: Self.player([
            Self.track("en"),
            Self.track("en", asr: true),
            Self.track("de", host: "example.com"),
        ]))
        #expect(tracks.map(\.languageCode) == ["en", "en"])
        #expect(tracks.map(\.isAutoGenerated) == [false, true])
        #expect(tracks.first?.name == "EN")
        #expect(YouTubeCaptionsParser.tracks(fromPlayer: [:]).isEmpty)
    }

    @Test("Written captions in the user's language win, then written English, then speech recognition")
    func choosesTrack() {
        let german = Self.transcriptTrack("de-DE")
        let english = Self.transcriptTrack("en")
        let asr = Self.transcriptTrack("ja", asr: true)
        let all = [asr, english, german]
        #expect(YouTubeCaptionsParser.preferredTrack(among: all, preferredLanguages: ["de-AT"]) == german)
        #expect(YouTubeCaptionsParser.preferredTrack(among: all, preferredLanguages: ["fr"]) == english)
        #expect(YouTubeCaptionsParser.preferredTrack(among: [asr, german], preferredLanguages: ["fr"]) == asr)
        #expect(YouTubeCaptionsParser.preferredTrack(among: [], preferredLanguages: ["en"]) == nil)
    }

    @Test("A track is fetched as json3 and read as one paragraph")
    func readsJSON3() throws {
        let track = try #require(YouTubeCaptionsParser.tracks(fromPlayer: Self.player([Self.track("en")])).first)
        let url = try #require(YouTubeCaptionsParser.jsonURL(for: track))
        let items = URLComponents(url: url, resolvingAgainstBaseURL: false)?.queryItems ?? []
        #expect(items.filter { $0.name == "fmt" }.map(\.value) == ["json3"])
        #expect(items.contains { $0.name == "v" && $0.value == "video01" })

        let json: [String: Any] = ["events": [
            ["tStartMs": 0, "segs": [["utf8": "Hello"], ["utf8": " there,\n"]]],
            ["tStartMs": 1200],
            ["tStartMs": 2000, "segs": [["utf8": "general  Kenobi."]]],
        ]]
        #expect(YouTubeCaptionsParser.transcript(fromJSON3: json) == "Hello there, general Kenobi.")

        // Written captions: one cue per event, no space at the end of a cue.
        let written: [String: Any] = ["events": [
            ["tStartMs": 0, "segs": [["utf8": "Hi everyone"]]],
            ["tStartMs": 1500, "segs": [["utf8": "welcome back"]]],
        ]]
        #expect(YouTubeCaptionsParser.transcript(fromJSON3: written) == "Hi everyone welcome back")
    }

    @Test("A long transcript is split at word boundaries by estimated tokens and sampled from start to end")
    func splitsTranscript() {
        let words = (1 ... 100).map { "word\($0)" }
        let text = words.joined(separator: " ")
        let parts = YouTubeVideoSummaryPlan.parts(of: text, budget: 20, maximumParts: 50)
        #expect(parts.count > 1)
        #expect(parts.allSatisfy { YouTubeVideoSummaryPlan.estimatedTokens($0) <= 20 })
        #expect(parts.joined(separator: " ") == text)

        let sampled = YouTubeVideoSummaryPlan.parts(of: text, budget: 20, maximumParts: 4)
        #expect(sampled.count == 4)
        #expect(sampled.first == parts.first)
        #expect(sampled.last == parts.last)
        #expect(YouTubeVideoSummaryPlan.parts(of: "short").count == 1)
    }

    @Test("Chinese, Japanese, and Korean count about a token per character, and a run without spaces is cut")
    func splitsTextWithoutSpaces() {
        #expect(YouTubeVideoSummaryPlan.estimatedTokens("日本語のテキスト") == 8)
        #expect(YouTubeVideoSummaryPlan.estimatedTokens("한국어") == 3)
        #expect(YouTubeVideoSummaryPlan.estimatedTokens("abcd") < 2)

        let japanese = String(repeating: "今日はコーヒーの話です。", count: 400)
        let parts = YouTubeVideoSummaryPlan.parts(of: japanese, maximumParts: 50)
        #expect(parts.count >= 3)
        #expect(parts.allSatisfy { YouTubeVideoSummaryPlan.estimatedTokens($0) <= YouTubeVideoSummaryPlan.partTokenBudget })
        #expect(parts.joined() == japanese)
    }

    @Test("Summarizing reads the chosen track and reports progress until done")
    func summarizes() async {
        let client = MockYouTubeClient()
        let english = Self.transcriptTrack("en")
        client.transcriptTracks["video01"] = [Self.transcriptTrack("ja", asr: true), english]
        client.transcripts[english.baseURL] = String(repeating: "Words said in the video. ", count: 20)
        var progress: [YouTubeVideoSummaryViewModel.State] = []
        var model: YouTubeVideoSummaryViewModel?
        model = YouTubeVideoSummaryViewModel(videoId: "video01", client: client, preferredLanguages: ["en-US"]) { title, transcript, onProgress in
            #expect(title == "A video")
            #expect(transcript.hasPrefix("Words said"))
            onProgress(.readingPart(1, of: 2))
            progress.append(model?.state ?? .idle)
            onProgress(.writing(YouTubeVideoSummary(overview: "It is", keyPoints: [])))
            progress.append(model?.state ?? .idle)
            return YouTubeVideoSummary(overview: "It is about words.", keyPoints: ["Words"])
        }
        await model?.run(title: "A video")
        #expect(client.transcriptRequests == [english])
        #expect(progress == [.readingPart(1, of: 2), .writing(YouTubeVideoSummary(overview: "It is", keyPoints: []))])
        #expect(model?.state == .done(YouTubeVideoSummary(overview: "It is about words.", keyPoints: ["Words"])))
    }

    @Test("No captions, or too little in them, says so without asking Apple Intelligence")
    func noCaptions() async {
        let client = MockYouTubeClient()
        var asked = false
        let model = YouTubeVideoSummaryViewModel(videoId: "video01", client: client) { _, _, _ in
            asked = true
            return YouTubeVideoSummary(overview: "", keyPoints: [])
        }
        await model.run(title: "A video")
        #expect(model.state == .failed(.noCaptions))

        let english = Self.transcriptTrack("en")
        client.transcriptTracks["video01"] = [english]
        client.transcripts[english.baseURL] = "[Music]"
        await model.run(title: "A video")
        #expect(model.state == .failed(.noCaptions))
        #expect(!asked)
    }

    @Test("A cancelled summary writes nothing afterwards, even when its fetch fails late")
    func cancelledRunStaysQuiet() async {
        let client = MockYouTubeClient()
        let english = Self.transcriptTrack("en")
        client.transcriptTracks["video01"] = [english]
        client.transcripts[english.baseURL] = String(repeating: "Words said in the video. ", count: 20)
        var model: YouTubeVideoSummaryViewModel?
        model = YouTubeVideoSummaryViewModel(videoId: "video01", client: client) { _, _, onProgress in
            // The page goes away mid-way, then the work fails the way a
            // cancelled URLSession fetch does.
            model?.cancel()
            onProgress(.readingPart(1, of: 2))
            throw URLError(.cancelled)
        }
        await model?.run(title: "A video")
        #expect(model?.state == .idle)
    }

    @Test("What Apple Intelligence declines, and other failures, end in a message")
    func failures() async {
        let client = MockYouTubeClient()
        let english = Self.transcriptTrack("en")
        client.transcriptTracks["video01"] = [english]
        client.transcripts[english.baseURL] = String(repeating: "Words said in the video. ", count: 20)

        let declined = YouTubeVideoSummaryViewModel(videoId: "video01", client: client) { _, _, _ in
            throw YouTubeVideoSummaryError.declined
        }
        await declined.run(title: "A video")
        #expect(declined.state == .failed(.declined))

        client.error = YTMusicError.networkError(underlying: URLError(.notConnectedToInternet))
        let offline = YouTubeVideoSummaryViewModel(videoId: "video01", client: client) { _, _, _ in
            YouTubeVideoSummary(overview: "", keyPoints: [])
        }
        await offline.run(title: "A video")
        #expect(offline.state == .failed(.other))
    }
}
